def test_composition_rows_epochs_and_migration_survive_cli_backup_and_restore(tmp_path):
    """Backup and restore stay with the host CLI (v2 §5); a restored pre-#1024
    inventory gains its state row on the next start."""
    import os
    import sqlite3
    from tests.test_workspace_production import ROOT, _cli, _env, _workspace
    root = _workspace(tmp_path)
    (root / "seraph.db").unlink()
    engine = _sync_db(root / "seraph.db", PRE_STATE_DOMAINS)
    with engine.begin() as connection:
        connection.execute(text("UPDATE runtime_composition_states SET epoch = 3 "
                                "WHERE runtime_domain = 'seraph.memory.v1'"))
    engine.dispose()
    environment = {**os.environ, **_env(root), "PYTHONPATH": str(ROOT / "backend")}
    archive = _cli(tmp_path, environment, "backup", "--archive", "pre-a31.zip")
    with sqlite3.connect(root / "seraph.db") as database:
        database.execute("DELETE FROM runtime_composition_states")
    _cli(tmp_path, environment, "restore", "--archive", archive["archive_path"], "--confirm")
    restored = create_engine(f"sqlite:///{root / 'seraph.db'}")
    with restored.connect() as connection:
        epochs = dict(connection.execute(text(
            "SELECT runtime_domain, epoch FROM runtime_composition_states")).all())
    assert set(epochs) == set(PRE_STATE_DOMAINS) and epochs["seraph.memory.v1"] == 3
    with restored.begin() as connection:
        assert _upgrade(connection) == (0, [], True)
    rows, events = _rows(restored)
    restored.dispose()
    assert set(rows) == set(DOMAINS) and len(events) == 1 and rows["seraph.memory.v1"][1] == 3


@pytest.mark.asyncio
@pytest.mark.parametrize("domain", sorted(PYTHON_HOSTED_DOMAINS))
@pytest.mark.parametrize("change", [{"owner_kind": "cordis"}, {"composition_digest": "c" * 64},
                                    {"owner_kind": "cordis", "composition_digest": "c" * 64}])
async def test_a_tampered_python_hosted_row_fails_the_whole_inventory(service_db, domain, change):
    """A restored or edited row naming another owner never passes state readiness or binding."""
    from sqlalchemy import update
    from src.runtime_plugins.ownership import inventory
    from src.runtime_plugins.worker import ProviderActivationError, _state_predicate
    async with get_session() as db:
        await db.execute(update(RuntimeCompositionState).where(RuntimeCompositionState.runtime_domain == domain)
                         .values(**change))
    async with get_session() as db:
        with pytest.raises(CompositionBindingError) as excinfo:
            await inventory(db)
        assert excinfo.value.reason_code == "composition_inventory_invalid"
        with pytest.raises(CompositionBindingError):
            await bind_invocation(db, method="memory.retrieve", native_branch="artifact")
    with pytest.raises(ProviderActivationError) as activation:
        await _state_predicate(run_init=False)
    assert activation.value.reason_code == "composition_inventory_invalid"
