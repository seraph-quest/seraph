@pytest.mark.parametrize("raw", [raw for _, raw in _committed()], ids=[name for name, _ in _committed()])
def test_committed_pre_state_bindings_round_trip_byte_identically(raw):
    binding = RuntimeCompositionBinding.from_json(raw)
    assert binding.schema_version in {1, 2} and binding.method_manifest_version == MANIFEST_VERSION_V1
    assert STATE_DOMAIN not in {item.runtime_domain for item in binding.dependency_vector}
    assert binding.to_json() == raw
    assert binding.binding_digest == json.loads(raw)["binding_digest"]
