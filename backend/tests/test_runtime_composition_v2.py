def _sync_db(path: Path, domains):
    engine = create_engine(f"sqlite:///{path}")
    SQLModel.metadata.create_all(engine)
    with engine.begin() as connection:
        for domain in domains:
            connection.execute(text(
                "INSERT INTO runtime_composition_states (runtime_domain, owner_kind, epoch, composition_digest, "
                "state, recovery_receipt_ref) VALUES (:d, 'legacy', 1, :g, 'ready', NULL)"),
                {"d": domain, "g": legacy_composition_digest(domain) if domain in DOMAINS else "e" * 64})
    return engine


def _rows(engine):
    with engine.connect() as connection:
        rows = {row[0]: tuple(row[1:]) for row in connection.execute(text(
            "SELECT runtime_domain, owner_kind, epoch, composition_digest, state, recovery_receipt_ref "
            "FROM runtime_composition_states"))}
        events = [json.loads(item) for item in connection.execute(text(
            "SELECT details_json FROM audit_events WHERE event_type = 'runtime_composition_domain_introduced'"))
            .scalars().all()]
    return rows, [item for item in events if item["runtime_domain"] == STATE_DOMAIN]


def _upgrade(connection):
    """``init_db``'s order: seed an empty table, #1020 introductions, then the state step."""
    return (seed_legacy_inventory_sync(connection), introduce_domains_sync(connection),
            introduce_state_domain_sync(connection))


def test_exact_pre_a31_inventory_gains_one_state_row_and_audit_event(tmp_path):
    engine = _sync_db(tmp_path / "pre.db", PRE_STATE_DOMAINS)
    with engine.begin() as connection:
        connection.execute(text("UPDATE runtime_composition_states SET epoch = 4, state = 'blocked' "
                                "WHERE runtime_domain = 'seraph.memory.v1'"))
    before, _ = _rows(engine)
    with engine.begin() as connection:
        assert _upgrade(connection) == (0, [], True)
    with engine.begin() as connection:
        assert _upgrade(connection) == (0, [], False)  # idempotent: audited once
    rows, events = _rows(engine)
    assert set(rows) == set(DOMAINS) and len(events) == 1
    assert events[0]["introduced_by"] == "1024" and events[0]["owner_kind"] == "legacy"
    assert rows[STATE_DOMAIN] == ("legacy", 1, legacy_composition_digest(STATE_DOMAIN), "ready", None)
    # Existing owners stay byte-identical.
    assert {domain: rows[domain] for domain in before} == before


def test_chained_steps_bring_a_pre_1020_inventory_to_the_full_set(tmp_path):
    """#1019-era inventories gain #1020's domains, then exactly then the state domain."""
    originals = tuple(domain for domain in PRE_STATE_DOMAINS if domain not in DOMAIN_INTRODUCTIONS)
    assert len(originals) == 14
    engine = _sync_db(tmp_path / "pre1020.db", originals)
    with engine.begin() as connection:
        seeded, introduced, state = _upgrade(connection)
    assert (seeded, sorted(introduced), state) == (0, sorted(DOMAIN_INTRODUCTIONS), True)
    rows, events = _rows(engine)
    assert set(rows) == set(DOMAINS) and len(events) == 1


def test_empty_inventory_is_seeded_whole_including_state(tmp_path):
    engine = _sync_db(tmp_path / "fresh.db", ())
    with engine.begin() as connection:
        assert _upgrade(connection) == (len(DOMAINS), [], False)
    rows, events = _rows(engine)
    assert set(rows) == set(DOMAINS) and len(DOMAINS) == 19 and events == []


